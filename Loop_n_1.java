import java.util.*;

public class Loop_n_1
{
    public static void main(String [] args)
    {
        Scanner sc =new Scanner(System.in);

        System.out.println("enter one number ");
        int n =sc.nextInt();

        for(int i=n;i>=1;i--)
        {
        System.out.println(i);
        }
    }
}