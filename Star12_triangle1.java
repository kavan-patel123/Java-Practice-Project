
import java.util.*;

public class Star12_triangle1
{
    public static void main(String [] args)
    {
        Scanner sc =new Scanner(System.in);

        int n =sc.nextInt();
    

        for(int r=1;r<=n;r++)
        {
            for(int c=n;c>=1;c--)
            {
                System.out.print("p"); //uppercase ABC...
            }
            System.out.println( );
        }
        // System.out.println( );
    }
}